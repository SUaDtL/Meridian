import { createHash } from 'node:crypto';
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, join, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const lockText = await readFile(join(root, 'package-lock.json'), 'utf8');
const lock = JSON.parse(lockText);
const application = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'));
if (!lock.packages || ![2, 3].includes(lock.lockfileVersion)) {
  throw new Error('Expected a package-lock v2/v3 packages inventory.');
}

const compare = (a, b) => a < b ? -1 : a > b ? 1 : 0;
const filesAreNotices = name => /^(?:licen[cs]e|notice|copying)(?:[. _-].*)?$/i.test(name) ||
  /^third[-_ ]?party[-_ ]?(?:licen[cs]es?|notice(?:s|text)?)(?:[. _-].*)?$/i.test(name);
const formatLicense = value => typeof value === 'string' ? value : value === undefined ? 'Not declared' : JSON.stringify(value);
const entries = Object.entries(lock.packages).filter(([path]) => path !== '').sort(([a], [b]) => compare(a, b));
const sections = [];
let installedCount = 0;
let copiedFiles = 0;

for (const [packagePath, locked] of entries) {
  const directory = resolve(root, packagePath);
  if (!packagePath.startsWith('node_modules/') || !directory.startsWith(root + sep)) {
    throw new Error(`Unsupported dependency location in lockfile: ${packagePath}`);
  }
  let metadata;
  try {
    metadata = JSON.parse(await readFile(join(directory, 'package.json'), 'utf8'));
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
  if (metadata && locked.version && metadata.version !== locked.version) {
    throw new Error(`${packagePath} is ${metadata.version}, but the lockfile specifies ${locked.version}. Run npm ci before generating notices.`);
  }
  if (metadata) installedCount++;
  const fallbackName = packagePath.slice(packagePath.lastIndexOf('node_modules/') + 'node_modules/'.length);
  const name = metadata?.name ?? locked.name ?? fallbackName;
  const version = metadata?.version ?? locked.version ?? 'Unspecified';
  const license = metadata?.license ?? metadata?.licenses ?? locked.license;
  const section = [
    '='.repeat(78),
    `${name} @ ${version}`,
    `Lockfile location: ${packagePath}`,
    `Declared license: ${formatLicense(license)}`,
    `Dependency scope: ${locked.dev ? 'development/build/test' : 'runtime or transitive'}${locked.optional ? '; optional' : ''}`,
  ];

  if (!metadata) {
    section.push(
      'Installed metadata: unavailable in this installation.',
      'This lockfile package is not installed here, commonly because an optional',
      'dependency targets a different platform. Its metadata is recorded from the',
      'lockfile; no local license text is available to reproduce.',
    );
  } else {
    const rootFiles = (await readdir(directory, { withFileTypes: true }))
      .filter(entry => entry.isFile() && filesAreNotices(entry.name))
      .map(entry => entry.name).sort(compare);
    if (!rootFiles.length) section.push('No root LICENSE, LICENCE, NOTICE, COPYING, or third-party notice file was found in this installed package.');
    for (const filename of rootFiles) {
      const text = new TextDecoder('utf-8', { fatal: true }).decode(await readFile(join(directory, filename)));
      section.push('', `----- BEGIN ${packagePath}/${filename} -----`, text,
        `----- END ${packagePath}/${filename} -----`);
      copiedFiles++;
    }
  }
  sections.push(section.join('\n'));
}

const header = [
  'MERIDIAN THIRD-PARTY DEPENDENCY NOTICES',
  '',
  `Application: ${application.name} ${application.version}`,
  `Lockfile SHA-256: ${createHash('sha256').update(lockText).digest('hex')}`,
  `Inventory: ${entries.length} lockfile package locations; ${installedCount} installed; ${copiedFiles} notice files reproduced.`,
  '',
  'Scope: every package recorded in package-lock.json, including development,',
  'build, test, transitive, and platform-specific optional dependencies. This',
  'inventory is deliberately broader than the application bundle. It is not a',
  'claim that every listed dependency is included in the distributed runtime.',
  '',
  'Names, versions, and license declarations come from matching installed package',
  'metadata when available and from the lockfile otherwise. Root license/notice',
  'files from installed packages are reproduced below without rewriting their',
  'contents. Missing platform packages and missing local notice files are stated',
  'explicitly. No network retrieval is used by this generator.',
  '',
  'Generated by scripts/third-party-notices.mjs. Rebuild with npm run licenses',
  'after installing the exact lockfile dependencies with npm ci.',
  '',
].join('\n');

const output = join(root, 'public', 'THIRD-PARTY-NOTICES.txt');
await mkdir(dirname(output), { recursive: true });
await writeFile(output, `${header}\n${sections.join('\n\n')}\n`, 'utf8');
console.log(`Dependency notices: ${entries.length} lockfile package locations, ${installedCount} installed, ${copiedFiles} reproduced files.`);
console.log(output);
